/// The README table rendered from the registry, markers included.
pub fn render() -> String {
  let mut out = String::new();
  out.push_str(BEGIN);
  out.push('\n');
  out.push_str("| Capability | Status | Where | Limits | Proven by |\n|---|---|---|---|---|\n");
  for row in CAPABILITIES {
    let proof = if row.evidence.is_empty() {
      "—".to_owned()
    } else {
      row
        .evidence
        .iter()
        .map(|evidence| format!("`{}` ({})", evidence.test, evidence.file))
        .collect::<Vec<_>>()
        .join("<br>")
    };
    out.push_str(&format!(
      "| {} | {} | {} | {} | {} |\n",
      row.name,
      row.status.label(),
      row.r#where,
      row.limits,
      proof
    ));
  }
  out.push_str(END);
  out
}

/// The README's table block, markers included, if it has one.
fn readme_block(readme: &str) -> Option<&str> {
  let start = readme.find(BEGIN)?;
  let end = readme
    .get(start..)?
    .find(END)?
    .checked_add(start)?
    .checked_add(END.len())?;
  readme.get(start..end)
}

/// Every reason the registry or the README is out of step (empty when in step).
pub fn problems(root: &Path) -> Vec<String> {
  let mut problems = Vec::new();
  for row in CAPABILITIES {
    match row.status {
      Status::Works | Status::Limited if row.evidence.is_empty() => {
        problems.push(format!(
          "capability `{}` claims to work but cites no test",
          row.name
        ));
      }
      Status::Owed if !row.limits.contains("AUD-") && !row.limits.contains("GAP") => {
        problems.push(format!("owed capability `{}` names no gap", row.name));
      }
      _ => {}
    }
    for evidence in row.evidence {
      if let Some(problem) = evidence_problem(root, evidence) {
        problems.push(format!("capability `{}`: {problem}", row.name));
      }
    }
  }
  match std::fs::read_to_string(root.join("README.md")) {
    Ok(readme) => match readme_block(&readme) {
      Some(block) if block == render() => {}
      Some(_) => problems.push(
        "README.md's capability table differs from the registry; run `cargo xtask capabilities --write`"
          .to_owned(),
      ),
      None => problems.push("README.md has no capability table markers".to_owned()),
    },
    Err(error) => problems.push(format!("README.md: {error}")),
  }
  problems
}

/// Why `evidence` is not a runnable test in the tree, if it is not.
fn evidence_problem(root: &Path, evidence: &Evidence) -> Option<String> {
  let source = match std::fs::read_to_string(root.join(evidence.file)) {
    Ok(source) => source,
    Err(_) => return Some(format!("{} does not exist", evidence.file)),
  };
  let declaration = if evidence.file.ends_with(".rs") {
    format!("fn {}(", evidence.test)
  } else if evidence.file.ends_with(".py") {
    format!("def {}(", evidence.test)
  } else {
    format!("test('{}'", evidence.test)
  };
  let Some(at) = source.find(&declaration) else {
    return Some(format!(
      "{} declares no test `{}`",
      evidence.file, evidence.test
    ));
  };
  if evidence.file.ends_with(".rs") {
    // The attributes directly above the function: `#[test]` must be there, `#[ignore]` must not.
    let above = source.get(..at).unwrap_or("");
    let attributes: Vec<&str> = above
      .lines()
      .rev()
      .skip_while(|line| line.trim().is_empty())
      .take_while(|line| {
        let line = line.trim();
        line.starts_with("#[") || line.starts_with("///") || line.starts_with("//")
      })
      .collect();
    if !attributes.iter().any(|line| line.trim() == "#[test]") {
      return Some(format!(
        "`{}` in {} is not a #[test]",
        evidence.test, evidence.file
      ));
    }
    if attributes
      .iter()
      .any(|line| line.trim().starts_with("#[ignore"))
    {
      return Some(format!(
        "`{}` in {} is #[ignore]d",
        evidence.test, evidence.file
      ));
    }
  }
  None
}

/// Rewrites the README's table from the registry.
pub fn write(root: &Path) -> Result<(), String> {
  let path = root.join("README.md");
  let readme = std::fs::read_to_string(&path).map_err(|e| format!("README.md: {e}"))?;
  let block = readme_block(&readme).ok_or("README.md has no capability table markers")?;
  let updated = readme.replacen(block, &render(), 1);
  // The development tool rewriting the tree's own README (not a host path of the product).
  #[allow(clippy::disallowed_methods)]
  std::fs::write(&path, updated).map_err(|e| format!("README.md: {e}"))
}

#[cfg(test)]
mod tests {
  use super::*;

  /// AUD-29-32. Do: check the registry against the tree. Expect: every cited test exists, is a test and
  /// is not ignored, and every owed row names its gap — the same check `cargo xtask check` runs, minus the
  /// README comparison.
  #[test]
  fn every_cited_test_exists_and_runs() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
    let problems: Vec<String> = problems(root)
      .into_iter()
      .filter(|problem| !problem.starts_with("README.md"))
      .collect();
    assert!(problems.is_empty(), "{problems:#?}");
  }

  /// AUD-29-32. Do: point a row at a test that does not exist, and at one that is ignored. Expect: both
  /// reported, so a renamed, removed or ignored proof cannot keep a capability looking proven.
  #[test]
  fn a_missing_or_ignored_proof_is_reported() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
    let missing = ev("crates/cli/tests/cli.rs", "no_such_test_anywhere");
    assert!(evidence_problem(root, &missing).is_some());
    let ignored = ev(
      "crates/cluster/tests/publication_cost.rs",
      "a_publication_costs_the_clone_the_encoding_and_the_hash_of_the_whole_state",
    );
    assert!(evidence_problem(root, &ignored).unwrap().contains("ignore"));
  }
}
