//! The capability table (AUD-29-32): what slates does today, where, with what limits, and the executable
//! acceptance tests that prove each row. The README's status table is rendered from this registry and
//! `cargo xtask check` refuses a README whose table differs from the rendering, a cited test that does not
//! exist, or one marked `#[ignore]` — so the published capability text cannot drift from the reviewed
//! evidence without the check failing. `cargo xtask capabilities --write` regenerates the README's table
//! after the registry changes. A row's status is a reviewed judgement, stated with its limits; the check makes
//! sure the evidence it cites stays real, not that the judgement is right.

use std::path::Path;

/// Format: the marker opening the rendered table in the README.
pub const BEGIN: &str =
  "<!-- capabilities:begin (generated by `cargo xtask capabilities --write`; do not edit) -->";
/// Format: the marker closing it.
pub const END: &str = "<!-- capabilities:end -->";

/// How far a capability works today.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Status {
  /// Works as described, proven by the cited tests.
  Works,
  /// Works within the stated limits, proven by the cited tests.
  Limited,
  /// Not built; the limits name the gap that tracks it.
  Owed,
}

impl Status {
  fn label(self) -> &'static str {
    match self {
      Status::Works => "works",
      Status::Limited => "limited",
      Status::Owed => "owed",
    }
  }
}

/// One acceptance test: the file, and the test's name as it is declared there (a Rust `fn`, a Python
/// `def`, or a Node `test('…')` title).
#[derive(Clone, Copy, Debug)]
pub struct Evidence {
  pub file: &'static str,
  pub test: &'static str,
}

/// One row of the table.
#[derive(Clone, Copy, Debug)]
pub struct Capability {
  pub name: &'static str,
  pub status: Status,
  pub r#where: &'static str,
  pub limits: &'static str,
  pub evidence: &'static [Evidence],
}

const fn ev(file: &'static str, test: &'static str) -> Evidence {
  Evidence { file, test }
}

