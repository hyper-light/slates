/// Reference descriptor for one of Marc Stevens's 32 SHA-1 disturbance vectors.
pub(super) struct DvInfo {
  /// Disturbance-vector family (`1` for type I, `2` for type II).
  pub(super) dv_type: u32,
  /// Disturbance-vector step parameter `K`.
  pub(super) dv_k: u32,
  /// Disturbance-vector bit parameter `b`.
  pub(super) dv_b: u32,
  /// Intermediate recompression step (`58` or `65`).
  pub(super) test_step: u32,
  /// Mask bit position (`0..32`) returned by [`ubc_check`].
  pub(super) mask_bit: usize,
  /// Full 80-word expanded message XOR difference `dm[80]`.
  pub(super) dm: [u32; 80],
}

