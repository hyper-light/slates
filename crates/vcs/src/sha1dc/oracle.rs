/// Independent FIPS 180-4 §6.1.2 SHA-1 80-word message schedule expansion.
pub(super) fn expand_ref(block: &[u8; 64]) -> [u32; 80] {
  let mut w = [0u32; 80];
  for t in 0..16 {
    w[t] = u32::from_be_bytes([
      block[4 * t],
      block[4 * t + 1],
      block[4 * t + 2],
      block[4 * t + 3],
    ]);
  }
  for t in 16..80 {
    w[t] = (w[t - 3] ^ w[t - 8] ^ w[t - 14] ^ w[t - 16]).rotate_left(1);
  }
  w
}

/// Independent FIPS 180-4 §6.1.2 SHA-1 single-block compression.
pub(super) fn compress_ref(ihv: &mut [u32; 5], block: &[u8; 64]) {
  let w = expand_ref(block);
  let [mut a, mut b, mut c, mut d, mut e] = *ihv;
  for (t, &word) in w.iter().enumerate() {
    let (f, k) = match t {
      0..=19 => ((b & c) | (!b & d), 0x5a82_7999u32),
      20..=39 => (b ^ c ^ d, 0x6ed9_eba1u32),
      40..=59 => ((b & c) | (b & d) | (c & d), 0x8f1b_bcdcu32),
      _ => (b ^ c ^ d, 0xca62_c1d6u32),
    };
    let next = a
      .rotate_left(5)
      .wrapping_add(f)
      .wrapping_add(e)
      .wrapping_add(k)
      .wrapping_add(word);
    e = d;
    d = c;
    c = b.rotate_left(30);
    b = a;
    a = next;
  }
  ihv[0] = ihv[0].wrapping_add(a);
  ihv[1] = ihv[1].wrapping_add(b);
  ihv[2] = ihv[2].wrapping_add(c);
  ihv[3] = ihv[3].wrapping_add(d);
  ihv[4] = ihv[4].wrapping_add(e);
}

/// Clears `bit` in `mask` if any condition in `failed` holds.
#[inline(always)]
fn clear_if_any(mask: u32, bit: u32, failed: &[bool]) -> u32 {
  if failed.iter().any(|&cond| cond) {
    mask & !bit
  } else {
    mask
  }
}

/// Reference `ubc_check` over an 80-word expanded SHA-1 schedule, bit-for-bit identical to `sha1-checked` 0.10.0.
